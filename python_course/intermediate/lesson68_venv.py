# Virtual environments in Python (venv)
# A virtual environment loads all your Python installation 
# into a folder in a chosen path.
# When activating a virtual environment, the venv installation will be used.
# Venv is a module that'll be used to create virtual environments.
# You can give the name you prefer to a virtual environment, but the most commons ones are:
# venv env .venv .env

# How to create a venv:
# python -m venv venv(virtual environment name)

# How to activate and deactivate venv:
# . venv/bin/activate or source ven/bin/activate # To activate
#  deactivate # To deactivate