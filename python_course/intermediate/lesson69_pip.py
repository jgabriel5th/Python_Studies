# pip is used to install modules from PyPi
# How to install with pip: pip install module_name
# How to uninstall with pip: pip uninstall module_name
# How to see available module versions: pip index versions module_name
# How to see what is installed: pip freeze
# How to create requirements or update it: pip freeze > requirements.txt
# How to install from requirements.txt: pip install -r .\requirements.txt